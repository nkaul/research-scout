import { test, expect } from '../../frontend/node_modules/@playwright/test';

test('actual fixture chat routes separate providers, reuses saved evidence and reopens without a search', async ({ page }) => {
  test.skip(process.env.SCOUT_BROWSER_INTEGRATION !== '1', 'Enable explicitly with real local fixture services.');
  const configuration = await page.request.get('/api/providers');
  expect(configuration.ok()).toBe(true);
  const providers = (await configuration.json()).providers;
  expect(providers.filter((p: { mode: string }) => p.mode === 'fixture')).toHaveLength(8);
  await page.goto('/');
  await page.getByRole('button', { name: 'Exploration chat', exact: true }).click();
  await page.getByRole('checkbox', { name: 'Choose sources manually', exact: true }).check();
  await page.getByRole('checkbox', { name: /Semantic Scholar/ }).check();
  await page.getByRole('textbox', { name: 'Exploration message', exact: true }).fill('Memory in autonomous research agents');
  await page.getByRole('button', { name: 'Explore', exact: true }).click();
  const firstTurn = page.getByTestId('exploration-turn').first();
  await expect(firstTurn.getByTestId('chat-source').first()).toBeVisible();
  await expect(firstTurn).toHaveAttribute('data-status', 'running');
  await expect(firstTurn).toHaveAttribute('data-status', 'succeeded', { timeout: 20_000 });
  const id = new URL(page.url()).searchParams.get('conversation');
  expect(id).toBeTruthy();
  const before = await (await page.request.get(`/api/conversations/${id}`)).json();
  expect(before.turns[0].run_ids).toHaveLength(2);
  expect(new Set(before.turns[0].sources.map((source: { provider: string }) => source.provider))).toEqual(new Set(['openalex', 'semantic_scholar']));
  expect(before.turns[0].usage.model_http_attempts).toBe(0);
  const runCount = (await (await page.request.get('/api/research-runs')).json()).runs.length;
  await page.getByLabel('Exploration action', { exact: true }).selectOption('saved');
  await page.getByRole('textbox', { name: 'Exploration message', exact: true }).fill('Show source 1');
  await page.getByRole('button', { name: 'Read saved sources', exact: true }).click();
  await expect(page.getByTestId('exploration-turn').nth(1)).toHaveAttribute('data-status', 'succeeded');
  const after = await (await page.request.get(`/api/conversations/${id}`)).json();
  expect(after.turns[1].sources).toHaveLength(1);
  expect(after.turns[1].run_ids).toHaveLength(0);
  expect(after.turns[1].usage.research_attempts).toBe(0);
  expect((await (await page.request.get('/api/research-runs')).json()).runs.length).toBe(runCount);
  const savedUrl = page.url();
  await page.reload();
  await expect(page.getByTestId('exploration-turn')).toHaveCount(2);
  expect(page.url()).toBe(savedUrl);
  expect((await (await page.request.get('/api/research-runs')).json()).runs.length).toBe(runCount);
  await page.getByTestId('exploration-turn').first().getByRole('button', { name: /^Open .+ in workspace$/ }).first().click();
  await expect(page.getByTestId('source-row').first()).toBeVisible();
  await expect(page.getByRole('button', { name: 'Search workspace', exact: true })).toHaveAttribute('aria-pressed', 'true');
});

test('actual fixture DOI chat routes to DataCite without creating a discovery run', async ({ page }) => {
  test.skip(process.env.SCOUT_BROWSER_INTEGRATION !== '1', 'Enable explicitly with real local fixture services.');
  const countBefore = (await (await page.request.get('/api/research-runs')).json()).runs.length;
  await page.goto('/');
  await page.getByRole('button', { name: 'Exploration chat', exact: true }).click();
  await page.getByRole('button', { name: 'Try a DataCite DOI', exact: true }).click();
  await page.getByRole('button', { name: 'Look up DOI', exact: true }).click();
  await expect(page.getByTestId('exploration-turn').first()).toHaveAttribute('data-status', 'succeeded');
  const id = new URL(page.url()).searchParams.get('conversation');
  const saved = await (await page.request.get(`/api/conversations/${id}`)).json();
  expect(saved.turns[0].sources[0].provider).toBe('datacite');
  expect(saved.turns[0].sources[0].registry_only).toBe(true);
  expect(saved.turns[0].run_ids).toHaveLength(0);
  expect((await (await page.request.get('/api/research-runs')).json()).runs.length).toBe(countBefore);
});
