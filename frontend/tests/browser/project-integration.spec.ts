import { test, expect } from '@playwright/test';
import { admitFixtureDiscovery } from './diagnostic-discovery';

test('a durable research project groups concepts, multiple real fixture queries and saved resources', async ({ page, request }) => {
  test.skip(process.env.SCOUT_BROWSER_INTEGRATION !== '1', 'Requires explicitly enabled isolated fixture services.');
  test.setTimeout(90_000);
  const providers = await (await request.get('/api/providers')).json();
  expect(providers.providers).toHaveLength(9);
  expect(providers.providers.every((item: { mode: string }) => item.mode === 'fixture')).toBe(true);
  const name = `Project acceptance ${Date.now()}`;
  await page.goto('/app');
  await page.getByRole('button', { name: /^Research projects/ }).click();
  const manager = page.getByRole('dialog', { name: 'Research projects', exact: true });
  await page.getByLabel('New research project name').fill(name);
  await manager.getByRole('button', { name: 'Create research project', exact: true }).click();
  await expect(manager.getByRole('heading', { name, exact: true })).toBeVisible();
  await manager.getByLabel('New concept name').fill('Retrieval quality');
  await manager.getByRole('button', { name: 'Create concept', exact: true }).click();
  await expect(manager.getByRole('button', { name: 'Retrieval quality', exact: true })).toBeVisible();
  await manager.getByRole('button', { name: 'Continue researching', exact: true }).click();
  await page.getByLabel('Active project concept').selectOption({ label: 'Retrieval quality' });
  const diagnostic = await admitFixtureDiscovery(request, 'Retrieval augmented generation context quality');
  const firstId = diagnostic.id;
  await page.goto(`/app?search=${firstId}`);
  await expect(page.getByTestId('search-results')).toHaveAttribute('data-status', /succeeded|partial/, { timeout: 40_000 });
  await page.getByLabel('Active project concept').selectOption({ label: 'Retrieval quality' });
  await page.getByRole('button', { name: 'Add current query to project', exact: true }).click();
  const first = page.getByTestId('search-result-card').first();
  await first.getByRole('button', { name: 'Save to project', exact: true }).click();
  await expect(first.getByRole('button', { name: 'Saved to project', exact: true })).toBeVisible();
  const projects = async () => (await (await request.get('/api/projects')).json()).projects;
  await expect.poll(async () => (await projects()).find((item: { name: string }) => item.name === name)?.queries.length).toBe(1);
  let project = (await projects()).find((item: { name: string }) => item.name === name);
  expect(project.resources).toHaveLength(1);
  expect(project.resources[0].concept_ids).toEqual([project.concepts[0].id]);
  expect(project.resources[0].observations[0].source.source_ref).toBe(project.resources[0].source_ref);
  const second = await admitFixtureDiscovery(request, 'Evaluating language model context selection');
  await page.goto(`/app?search=${second.id}`);
  await expect(page).not.toHaveURL(new RegExp(`search=${firstId}$`));
  await expect(page.getByTestId('search-results')).toHaveAttribute('data-status', /succeeded|partial/, { timeout: 40_000 });
  await page.getByLabel('Active project concept').selectOption({ label: 'Retrieval quality' });
  await page.getByRole('button', { name: 'Add current query to project', exact: true }).click();
  await expect.poll(async () => (await projects()).find((item: { name: string }) => item.name === name)?.queries.length).toBe(2);
  project = (await projects()).find((item: { name: string }) => item.name === name);
  const before = await (await request.get(`/api/conversations/${firstId}`)).json();
  await page.reload();
  await expect(page.getByLabel('Active research project')).toHaveValue(project.id);
  await page.getByRole('button', { name: /^Research projects/ }).click();
  await expect(manager.getByRole('heading', { name, exact: true })).toBeVisible();
  await expect(manager.locator('.project-query')).toHaveCount(2);
  await expect(manager.locator('.project-resource')).toHaveCount(1);
  await manager.locator('.project-query').filter({ hasText: 'Retrieval augmented generation context quality' }).click();
  await expect(page).toHaveURL(new RegExp(`search=${firstId}(?:&turn=[^&]+)?$`));
  await expect(page.getByTestId('search-result-card').first()).toBeVisible();
  const after = await (await request.get(`/api/conversations/${firstId}`)).json();
  expect(after.turns.at(-1).usage).toEqual(before.turns.at(-1).usage);
  expect(after.turns.at(-1).usage.model_http_attempts).toBe(0);
});
