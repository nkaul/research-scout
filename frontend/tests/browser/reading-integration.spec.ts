import { expect, test } from '@playwright/test';

test('actual fixture search reads saved README and persists repository notes without more acquisition', async ({ page, request }) => {
  test.skip(process.env.SCOUT_BROWSER_INTEGRATION !== '1', 'Requires the explicitly started isolated fixture services.');
  test.setTimeout(90_000);
  const providers = await (await request.get('/api/providers')).json();
  expect(providers.providers.every((provider: { mode: string }) => provider.mode === 'fixture')).toBe(true);
  const beforeCredits = await (await request.get('/api/economics')).json();
  await page.route('https://**/*', route => route.abort());
  await page.goto('/app');
  await page.getByRole('switch', { name: 'AI refinement', exact: true }).click();
  await page.getByLabel('Research question', { exact: true }).fill('retrieval language model evaluation');
  await page.getByRole('button', { name: 'Search', exact: true }).click();
  await expect(page).toHaveURL(/[?&]search=/);
  const parentId = new URL(page.url()).searchParams.get('search');
  await expect.poll(async () => (await (await request.get(`/api/conversations/${parentId}`)).json()).turns.at(-1).status, { timeout: 50_000 }).toMatch(/^(SUCCEEDED|PARTIAL|EMPTY)$/);
  const parent = await (await request.get(`/api/conversations/${parentId}`)).json();
  const searchId = parent.turns.at(-1).resource_jobs.repos.search_id;
  const beforeRepos = await (await request.get(`/api/repo-searches/${searchId}`)).json();
  expect(beforeRepos.records.some((record: { readme: { artifact_available?: boolean } }) => record.readme.artifact_available)).toBe(true);
  await page.getByRole('tab', { name: /^Repos/ }).click();
  await expect(page.getByTestId('search-information')).toHaveCount(1);
  const first = page.getByTestId('repo-card').first();
  await expect(first).toBeVisible();
  await first.getByRole('button', { name: 'Original saved README', exact: true }).click();
  await expect(first.getByTestId('readable-original')).toContainText('# Fixture repository');
  const reader = page.getByTestId('repo-reader');
  await expect(reader).toBeVisible();
  await page.screenshot({ path: '../.scout/reading-ui-fixture-repos.local.png' });
  await reader.getByRole('tab', { name: 'Notes', exact: true }).click();
  const note = reader.getByLabel('Your repository note', { exact: true });
  await expect(note).toBeEnabled();
  const text = 'Authored fixture note: inspect the saved retrieval architecture.';
  await note.fill(text);
  await reader.getByRole('button', { name: 'Save note', exact: true }).click();
  await expect(reader.getByText('Unsaved draft', { exact: true })).toHaveCount(0);
  await page.reload();
  await expect(page.getByTestId('repo-card').first()).toBeVisible();
  await page.getByTestId('repo-reader').getByRole('tab', { name: 'Notes', exact: true }).click();
  await expect(page.getByTestId('repo-reader').getByLabel('Your repository note', { exact: true })).toHaveValue(text);
  await page.screenshot({ path: '../.scout/reading-ui-fixture-notes.local.png' });
  await page.getByRole('tab', { name: /^Data/ }).click();
  await expect(page.getByTestId('dataset-card').first()).toBeVisible();
  await page.screenshot({ path: '../.scout/reading-ui-fixture-data.local.png' });
  const afterRepos = await (await request.get(`/api/repo-searches/${searchId}`)).json();
  expect(afterRepos).toEqual(beforeRepos);
  const afterCredits = await (await request.get('/api/economics')).json();
  expect(afterCredits).toEqual(beforeCredits);
});
