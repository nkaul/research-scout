import type { ProviderId, Source } from './api';

export type RelevanceLabel = 'relevant' | 'partial' | 'irrelevant' | 'unknown';
export type RelevanceAssessment = { source_ref: string; provider: string; version: string | number; run_id: string; label: RelevanceLabel; reason: string; round: number };
export type RetrievalState = {
  status: string;
  intent?: string;
  domain?: string;
  assumptions?: string[];
  lexical_query?: string;
  semantic_query?: string;
  rationale?: string;
  intent_frame?: { object_of_change: string; intervention: string | null; desired_outcome: string; boundary: string };
  keywords?: string[];
  tags?: string[];
  llm_requests?: { step: string; purpose: string; status: string; model: string; body: unknown; body_compacted?: boolean }[];
  source_requests?: { provider: string; run_id: string; round: number; branch: string; transport: string; tool?: string; query_input?: string; executed_arguments: unknown; semantic_execution?: string; query_policy?: unknown; status?: string; cache_hit?: boolean }[];
  policy?: string;
  current_provider?: string;
  provider_queries?: { provider: string; lexical_query: string; semantic_query: string; rationale: string }[];
  provider_quality?: Record<string, { relevant: number; partial: number; unknown: number; irrelevant: number; round: number; status: string; reason?: string }>;
  round?: number;
  max_rounds?: number;
  rejected_count?: number;
  assessments?: RelevanceAssessment[];
  query_history?: { provider?: string; round: number; lexical_query: string; semantic_query: string; reason: string }[];
  warnings?: string[];
};
export type RetrievalConfig = { enabled: boolean; ready: boolean; status?: string; blocked_reason?: string; model?: string; max_rounds?: number; max_model_calls?: number };
export type ChatSource = Source & { run_id: string; registry_only?: boolean; citation_label?: string; fictional?: boolean; abstract_truncated?: boolean; description_truncated?: boolean; preview_truncated?: boolean; abstract_chars_available?: number; relevance?: { label: RelevanceLabel; reason: string; score?: number; evidence_quote?: string }; retrieval_round?: number };
export type ProviderActivity = { provider: string; operation: string; status: string; attempts: number; source_count: number; access_location_count?: number };
export type AccessLocation = { url?: string | null; url_for_pdf?: string | null; url_for_landing_page?: string | null; license?: string | null; version?: string | null; host_type?: string | null; evidence?: string | null; is_best?: boolean };
export type AccessObservation = { provider: 'unpaywall'; mode: 'fixture' | 'live'; doi: string; is_oa: boolean; oa_status: string; best_oa_location: AccessLocation | null; oa_locations: AccessLocation[]; observed_at: string; version: string };
export type RoutingMode = 'auto' | 'manual';
export type CanonicalPaper = { paper_id: string; doi?: string | null; representative: ChatSource; observations: ChatSource[]; providers: string[]; access: { status: string; observation?: AccessObservation | null; reason?: string | null } };
export type AnswerConfig = {
  enabled: boolean;
  configured?: boolean;
  model?: string;
  profile?: string;
  status?: string;
  blocked_reason?: string;
};
export type ExplorationTurn = {
  id: string;
  message: string;
  action: 'discover' | 'saved' | 'lookup' | 'generate' | 'access';
  routing?: RoutingMode;
  eligible_providers?: string[];
  source_plan?: { provider: string; role: string; status: string; reason: string; health_status: string; mode: string; readiness?: string; last_error?: string }[];
  providers: string[];
  status: string;
  created_at: string;
  completed_at?: string;
  run_ids: string[];
  sources: ChatSource[];
  related_sources?: ChatSource[];
  papers?: CanonicalPaper[];
  history_compacted?: boolean;
  saved_result_counts?: { sources: number; papers: number; related_sources: number; llm_requests: number; source_requests: number; assessments: number };
  response: string;
  warnings: string[];
  usage: { research_attempts: number; model_http_attempts: number; model_cost_usd: number | null; model_cost_hold_usd?: number };
  plan: { routing: string; generation: string; intent?: string; model?: string };
  activity?: ProviderActivity[];
  provider_activity?: ProviderActivity[];
  citations?: { label: string; provider: string; run_id: string; source_ref: string; observation_version: string | number }[];
  generation?: { status: string; model: string; input_tokens?: number; output_tokens?: number; cost_usd?: number; reservation_usd?: number; omitted_source_count?: number; validation?: string | Record<string, unknown> };
  access?: AccessObservation | null;
  agentic?: boolean;
  retrieval?: RetrievalState | null;
};
export type Conversation = {
  routing?: RoutingMode;
  id: string;
  title: string;
  created_at: string;
  updated_at: string;
  revision: number;
  cursor: string;
  status: 'IDLE' | 'RUNNING';
  providers: ProviderId[];
  filters: { year_from?: number | null; year_to?: number | null };
  turns: ExplorationTurn[];
};
export type ConversationSummary = Pick<Conversation, 'id' | 'title' | 'updated_at' | 'status'>;
